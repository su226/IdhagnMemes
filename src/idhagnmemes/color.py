LONG_HEX_RE = re.compile(r"^#?([0-9a-fA-F]{6})$")
SHORT_HEX_RE = re.compile(r"^#?([0-9a-fA-F]{3})$")
RGB_RE = re.compile(
    r"^rgb\s*\(\s*"
    r"(2(?:5[0-5]|[0-4]\d)|1\d\d|[1-9]?\d)\s*(?:,|\s)\s*"
    r"(2(?:5[0-5]|[0-4]\d)|1\d\d|[1-9]?\d)\s*(?:,|\s)\s*"
    r"(2(?:5[0-5]|[0-4]\d)|1\d\d|[1-9]?\d)\s*\)$"
)
HSL_RE = re.compile(
    r"^hsl\s*\(\s*"
    r"(\d+(?:\.\d+)?)(?:deg)?\s*(?:,|\s)\s*"
    r"(100(?:\.0+)?|[1-9]\d(?:\.\d+)?)%\s*(?:,|\s)\s*"
    r"(100(?:\.0+)?|[1-9]\d(?:\.\d+)?)%\s*\)$"
)


def parse(src: str) -> Optional[tuple[int, int, int]]:
    if src in COLORS:
        v = COLORS[src]
        r = v >> 16
        g = (v >> 8) & 0xFF
        b = v & 0xFF
        return (r, g, b)
    if match := LONG_HEX_RE.match(src):
        v = int(match[1], 16)
        r = v >> 16
        g = (v >> 8) & 0xFF
        b = v & 0xFF
        return (r, g, b)
    if match := SHORT_HEX_RE.match(src):
        v = int(match[1], 16)
        r = v >> 8
        g = (v >> 4) & 0xF
        b = v & 0xF
        r = r << 4 | r
        g = g << 4 | g
        b = b << 4 | b
        return (r, g, b)
    if match := RGB_RE.match(src):
        r = int(match[1])
        g = int(match[2])
        b = int(match[3])
        return (r, g, b)
    if match := HSL_RE.match(src):
        h = float(match[1]) % 360 / 360
        s = float(match[2]) / 100
        l = float(match[3]) / 100  # noqa: E741
        r, g, b = hls_to_rgb(h, l, s)
        r = round(r * 255)
        g = round(g * 255)
        b = round(b * 255)
        return (r, g, b)
    return None
